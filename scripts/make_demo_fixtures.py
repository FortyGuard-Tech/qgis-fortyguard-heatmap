#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the SYNTHETIC demo fixtures shipped in fortyguard_heatmap/fixtures/.

The tiles mimic the documented FortyGuard tcm response schema (GeoJSON Polygon
tiles with `tile_id` plus either `temperature` or
`average_temperature`/`min_temperature`/`max_temperature`, values in °C) but the
numbers are invented with a smooth deterministic function. They are NOT a
FortyGuard analysis and must never be presented as one.

Usage:  python3 scripts/make_demo_fixtures.py
"""
import json
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "fortyguard_heatmap", "fixtures")

# Demo AOI: a small rectangle over lower Manhattan, matching the public
# FortyGuard documentation sample polygon (coordinates are lon, lat).
AOI = [[-74.0170, 40.7050], [-74.0030, 40.7050], [-74.0030, 40.7180], [-74.0170, 40.7180], [-74.0170, 40.7050]]
NOTE = "SYNTHETIC DEMO DATA generated by scripts/make_demo_fixtures.py - NOT a FortyGuard analysis."

NX, NY = 14, 13   # ~100 m tiles
LON0, LON1 = -74.0170, -74.0030
LAT0, LAT1 = 40.7050, 40.7180


def tiles():
    dlon = (LON1 - LON0) / NX
    dlat = (LAT1 - LAT0) / NY
    rnd = random.Random(42)
    k = 0
    for j in range(NY):
        for i in range(NX):
            x0, x1 = LON0 + i * dlon, LON0 + (i + 1) * dlon
            y0, y1 = LAT0 + j * dlat, LAT0 + (j + 1) * dlat
            u, v = i / (NX - 1), j / (NY - 1)
            # smooth "heat island": hot centre-east, cooler at the waterfront (west/south)
            base = 27.0 + 6.0 * math.exp(-((u - 0.65) ** 2 + (v - 0.55) ** 2) / 0.12) - 2.0 * (1 - u) * (1 - v)
            noise = rnd.uniform(-0.4, 0.4)
            ring = [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]]
            yield k, ring, round(base + noise, 4)
            k += 1


def feature(k, ring, props):
    return {"type": "Feature", "id": str(k), "properties": props,
            "geometry": {"type": "Polygon", "coordinates": [ring]}}


def stats_for(values):
    n = len(values)
    mean = sum(values) / n
    sd = math.sqrt(sum((v - mean) ** 2 for v in values) / n)
    srt = sorted(values)
    return {
        "temperature_stats": {"minimum": min(values), "maximum": max(values), "mean": round(mean, 4),
                              "standard_deviation": round(sd, 4)},
        "overall_temperature_distribution": [srt[0], srt[n // 4], srt[n // 2], srt[3 * n // 4], srt[-1]],
        "demo": True,
    }


def main():
    os.makedirs(OUT, exist_ok=True)

    # Single-hour schema: properties.temperature
    feats, vals = [], []
    for k, ring, t in tiles():
        feats.append(feature(k, ring, {"tile_id": k, "temperature": t}))
        vals.append(t)
    # one tile with a missing value to exercise NULL handling
    feats[5]["properties"]["temperature"] = None
    vals.pop(5)
    single = {"type": "FeatureCollection", "demo_note": NOTE, "features": feats, "demo_stats": stats_for(vals)}
    with open(os.path.join(OUT, "demo_result_single_hour.geojson"), "w") as fh:
        json.dump(single, fh)

    # Daily schema: average/min/max_temperature
    feats, vals = [], []
    for k, ring, t in tiles():
        avg = round(t - 4.0, 4)
        feats.append(feature(k, ring, {"tile_id": k, "average_temperature": avg,
                                       "min_temperature": round(avg - 6.5, 4),
                                       "max_temperature": round(t + 1.5, 4)}))
        vals.append(avg)
    daily = {"type": "FeatureCollection", "demo_note": NOTE, "features": feats, "demo_stats": stats_for(vals)}
    with open(os.path.join(OUT, "demo_result_daily.geojson"), "w") as fh:
        json.dump(daily, fh)

    aoi = {"type": "Feature", "properties": {"name": "Demo AOI (synthetic test area)", "demo": True},
           "geometry": {"type": "Polygon", "coordinates": [AOI]}}
    with open(os.path.join(OUT, "demo_aoi.geojson"), "w") as fh:
        json.dump(aoi, fh, indent=1)

    with open(os.path.join(OUT, "README.md"), "w") as fh:
        fh.write("# Demo fixtures (SYNTHETIC)\n\n" + NOTE + "\n\n"
                 "* `demo_aoi.geojson` - sample area (EPSG:4326), same rectangle as the public API docs example.\n"
                 "* `demo_result_single_hour.geojson` - %d tiles with `properties.temperature` (one NULL on purpose).\n"
                 "* `demo_result_daily.geojson` - %d tiles with `average_temperature`, `min_temperature`, `max_temperature`.\n\n"
                 "Values are invented with a smooth function and never came from the FortyGuard API.\n"
                 "Regenerate with `python3 scripts/make_demo_fixtures.py`.\n" % (NX * NY, NX * NY))
    print("wrote fixtures to", OUT)


if __name__ == "__main__":
    main()
